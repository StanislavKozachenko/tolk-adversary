/**
 * Emit a `*.adversarial.test.tolk` skeleton from a resolved {@link Contract}.
 *
 * M1 families (internal channel):
 *   - unknown opcode -> the contract must reject (asserted against the real
 *     "invalid message" error code when the ABI declares one);
 *   - truncated body per message (opcode only, fields missing) -> the contract
 *     must fail (cell underflow).
 *
 * For signature-gated contracts (the incoming body is a `bits512` signature plus
 * the request, with a public key in storage) the signature is checked before the
 * opcode, so each crafted request is signed with a deploy-time keypair whose
 * public key is placed in storage; otherwise the contract would reject at the
 * signature gate instead of the branch under test.
 *
 * The deploy is synthesized best-effort from the storage schema with placeholder
 * values. When every storage field has a concrete placeholder the generated
 * `deployTarget()` compiles and runs as-is; otherwise it degrades to a `// TODO`
 * stub for the maintainer to complete.
 */

import type { Contract, Field, HeaderField, HeaderRole, Message } from "./model";

export interface GenerateOptions {
  /** Import specifier for the contract wrapper, e.g. `../wrappers/JettonMinter.gen`. */
  wrapperModule: string;
  /** Import specifier for the storage struct's source, e.g. `../contracts/storage`. */
  storageModule: string;
}

const DEPLOY_VALUE = "1000000000"; // 1 TON in nanotons
const MSG_VALUE = "100000000"; // 0.1 TON in nanotons

interface Ctx {
  signed: boolean;
  publicKeyField: string | null;
}

export function generateAdversarialTests(contract: Contract, opts: GenerateOptions): string {
  const ctx: Ctx = {
    signed: contract.signature.wrapped && contract.signature.publicKeyField !== null,
    publicKeyField: contract.signature.publicKeyField,
  };
  const out: string[] = [];
  const internal = contract.messages.filter((m) => m.channel === "internal");
  const external = contract.messages.filter((m) => m.channel === "external");

  out.push(header(contract));
  out.push(imports(opts, ctx));
  out.push(deployTarget(contract, ctx));
  out.push(unknownOpcodeTest(contract, internal, ctx));
  for (const m of internal) {
    if (m.fields.length > 0 && m.opcode !== null) out.push(truncatedBodyTest(m, ctx));
  }

  // M2: replay-header validation (only reachable past the signature gate, and
  // only with a message that parses from the header alone).
  const headerMsg = internal.find((m) => m.headerOnlyParses && m.header !== null && m.opcode !== null);
  if (ctx.signed && headerMsg?.header) {
    out.push(...headerFamily(contract, headerMsg.opcode ?? 0, headerMsg.header));
  }

  // M2: cross-channel — an external-only opcode must be rejected on the internal entry.
  const ext = external.find((m) => m.opcode !== null);
  if (ext?.opcode != null && internal.length > 0) {
    out.push(crossChannelTest(contract, ext, ctx));
  }

  return out.join("\n\n") + "\n";
}

function header(c: Contract): string {
  return [
    "// Generated by tolk-adversary. Review the TODOs before relying on this file.",
    `// Adversarial (negative) tests for contract ${c.name}.`,
  ].join("\n");
}

function imports(opts: GenerateOptions, ctx: Ctx): string {
  const lines = [
    'import "@acton/emulation/network"',
    'import "@acton/emulation/testing"',
    'import "@acton/testing/expect"',
  ];
  if (ctx.signed) lines.push('import "@acton/crypto"');
  lines.push(`import "${opts.wrapperModule}"`, `import "${opts.storageModule}"`);
  return lines.join("\n");
}

function deployTarget(c: Contract, ctx: Ctx): string {
  const { structName, fields } = c.storage;
  const overrides = ctx.signed && ctx.publicKeyField ? { [ctx.publicKeyField]: "kp.publicKey" } : {};
  const literal = storageLiteral(structName, fields, overrides);

  if (literal === null || structName === null) {
    return [
      `// TODO: deploy ${c.name} with valid initial storage (could not synthesize it from the ABI).`,
      `fun deployTarget(): (${c.name}, address) {`,
      `    val deployer = testing.treasury("deployer");`,
      `    assert(false, 0) throw 0; // remove once deploy is implemented`,
      `    return (${c.name}.fromAddress(deployer.address), deployer.address);`,
      `}`,
    ].join("\n");
  }

  if (ctx.signed) {
    return [
      `// Best-effort deploy synthesized from the storage schema. A keypair is created`,
      `// and its public key stored, so crafted requests can be signed past the signature gate.`,
      `fun deployTarget(): (${c.name}, address, KeyPair) {`,
      `    val deployer = testing.treasury("deployer");`,
      `    val kp = crypto.generateKeyPair();`,
      `    val target = ${c.name}.fromStorage(${literal});`,
      `    target.deploy(deployer.address, { value: ${DEPLOY_VALUE} });`,
      `    return (target, deployer.address, kp);`,
      `}`,
    ].join("\n");
  }

  return [
    `// Best-effort deploy synthesized from the storage schema (placeholder values).`,
    `// Replace placeholders if a test needs the contract in a specific valid state.`,
    `fun deployTarget(): (${c.name}, address) {`,
    `    val deployer = testing.treasury("deployer");`,
    `    val target = ${c.name}.fromStorage(${literal});`,
    `    target.deploy(deployer.address, { value: ${DEPLOY_VALUE} });`,
    `    return (target, deployer.address);`,
    `}`,
  ].join("\n");
}

/** A `Struct { field: placeholder, ... }` literal, or null if any field can't be synthesized. */
function storageLiteral(
  structName: string | null,
  fields: Field[],
  overrides: Record<string, string>,
): string | null {
  if (structName === null) return null;
  if (fields.length === 0) return `${structName} {}`;
  const parts: string[] = [];
  for (const f of fields) {
    const v = overrides[f.name] ?? placeholder(f.ty);
    if (v === null) return null;
    parts.push(`${f.name}: ${v}`);
  }
  return `${structName} { ${parts.join(", ")} }`;
}

/** A compiling placeholder value for a field type, or null if none fits. */
function placeholder(ty: string): string | null {
  if (ty.endsWith("?")) return "null";
  if (ty === "coins" || ty === "int" || /^u?int\d+$/.test(ty)) return "0";
  if (ty === "bool") return "false";
  if (ty === "address") return "address.fromWorkchainAndHash(0, 0)";
  if (ty === "cell") return "beginCell().endCell()";
  if (ty.startsWith("map<")) return "[]";
  // Cell<T>, bitsN, nested structs, enums: cannot synthesize generically yet.
  return null;
}

function unknownOpcodeTest(c: Contract, internal: Message[], ctx: Ctx): string {
  const used = new Set(internal.map((m) => m.opcode).filter((o): o is number => o !== null));
  const candidates = [0xffffffff, 0xdeadbeef, 0xbaddc0de, 0xffff0000];
  const opcode = candidates.find((o) => !used.has(o)) ?? 0xffffffff;
  const assertion = rejectAssertion(invalidMessageCode(c));
  return testBody(
    "rejects an unknown opcode",
    `beginCell().storeUint(0x${opcode.toString(16)}, 32).endCell()`,
    assertion,
    ctx,
  );
}

function truncatedBodyTest(m: Message, ctx: Ctx): string {
  const op = (m.opcode ?? 0).toString(16);
  return testBody(
    `rejects a truncated ${m.name} body`,
    `beginCell().storeUint(0x${op}, 32).endCell()`,
    "expect(res).toHaveTx({ success: false }); // cell underflow (exit 9)",
    ctx,
    `// opcode only; the ${m.fields.length} field(s) after it are missing`,
  );
}

/** A test that deploys, sends `requestExpr` (signed when needed), and asserts. */
function testBody(
  title: string,
  requestExpr: string,
  assertion: string,
  ctx: Ctx,
  comment?: string,
): string {
  const lines = [`get fun \`test adversarial: ${title}\`() {`];
  if (comment) lines.push(`    ${comment}`);
  if (ctx.signed) {
    lines.push(
      `    val (target, from, kp) = deployTarget();`,
      `    val request = ${requestExpr};`,
      `    val signature = crypto.sign(kp.privateKey, request);`,
      `    val body = beginCell().storeSlice(signature).storeSlice(request.beginParse()).endCell();`,
      `    val res = target.sendAny(from, body, { value: ${MSG_VALUE} });`,
    );
  } else {
    lines.push(
      `    val (target, from) = deployTarget();`,
      `    val body = ${requestExpr};`,
      `    val res = target.sendAny(from, body, { value: ${MSG_VALUE} });`,
    );
  }
  lines.push(`    ${assertion}`, "}");
  return lines.join("\n");
}

/** Header-validation tests: wrong seqno (replay), expired, wrong subwallet id. */
function headerFamily(c: Contract, opcode: number, header: HeaderField[]): string[] {
  const tests: string[] = [];
  const has = (r: HeaderRole): boolean => header.some((h) => h.role === r);

  const seqnoErr = errorByName(c, /seqno/i);
  if (has("seqno") && seqnoErr !== null) {
    tests.push(
      headerTest("rejects a wrong seqno (replay protection)", opcode, header, "seqno", "1", seqnoErr),
    );
  }
  const expiredErr = errorByName(c, /expir|valid.?until/i);
  if (has("validUntil") && expiredErr !== null) {
    tests.push(
      headerTest("rejects an expired message", opcode, header, "validUntil", "blockchain.now() - 1", expiredErr),
    );
  }
  const subErr = errorByName(c, /subwallet/i);
  if (has("subwalletId") && subErr !== null) {
    tests.push(
      headerTest("rejects a wrong subwallet id", opcode, header, "subwalletId", "1", subErr),
    );
  }
  return tests;
}

/** One header test: a signed request whose header has one field set to a bad value. */
function headerTest(
  title: string,
  opcode: number,
  header: HeaderField[],
  role: HeaderRole,
  failValue: string,
  errorCode: number,
): string {
  return [
    `get fun \`test adversarial: ${title}\`() {`,
    "    val (target, from, kp) = deployTarget();",
    `    val request = ${headerRequestExpr(opcode, header, role, failValue)};`,
    "    val signature = crypto.sign(kp.privateKey, request);",
    "    val body = beginCell().storeSlice(signature).storeSlice(request.beginParse()).endCell();",
    "    val res = target.sendAny(from, body, { value: " + MSG_VALUE + " });",
    `    expect(res).toHaveTx({ success: false, exitCode: 0x${errorCode.toString(16)} });`,
    "}",
  ].join("\n");
}

/** `beginCell().storeUint(opcode).storeUint(each header field)...endCell()`. */
function headerRequestExpr(
  opcode: number,
  header: HeaderField[],
  targetRole: HeaderRole,
  failValue: string,
): string {
  const lines = ["beginCell()", `        .storeUint(0x${opcode.toString(16)}, 32)`];
  for (const h of header) {
    const value = h.role === targetRole ? failValue : defaultHeaderValue(h.role);
    lines.push(`        .storeUint(${value}, ${h.bits}) // ${h.name}`);
  }
  lines.push("        .endCell()");
  return lines.join("\n");
}

/** A header value that passes validation (so a single bad field is isolated). */
function defaultHeaderValue(role: HeaderRole): string {
  return role === "validUntil" ? "blockchain.now() + 1000" : "0";
}

function errorByName(c: Contract, re: RegExp): number | null {
  for (const [name, code] of c.errors) if (re.test(name)) return code;
  return null;
}

/** An external-only opcode fed to the internal entry must be rejected. */
function crossChannelTest(c: Contract, ext: Message, ctx: Ctx): string {
  return testBody(
    `rejects an external-only opcode on the internal entry (${ext.name})`,
    `beginCell().storeUint(0x${(ext.opcode ?? 0).toString(16)}, 32).endCell()`,
    rejectAssertion(invalidMessageCode(c)),
    ctx,
  );
}

/**
 * The error an unknown opcode triggers. Across the standard contracts this is
 * the `else => throw 0xFFFF` fall-through (InvalidMessage / InvalidOpcode), so
 * prefer 0xFFFF; fall back to a name that clearly means "unknown message".
 * `ERROR_INVALID_OP` and similar are deliberately not matched — they are raised
 * inside handlers, not on an unrecognized opcode.
 */
function invalidMessageCode(c: Contract): number | null {
  if (c.errors.some(([, code]) => code === 0xffff)) return 0xffff;
  for (const [name, code] of c.errors) {
    if (/invalid.?message|wrong.?op|unknown.?op/i.test(name)) return code;
  }
  return null;
}

function rejectAssertion(code: number | null): string {
  if (code === null) return "expect(res).toHaveTx({ success: false }); // TODO: confirm the exit code";
  return `expect(res).toHaveTx({ success: false, exitCode: 0x${code.toString(16)} });`;
}
